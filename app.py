import streamlit as st
import pandas as pd
import joblib

from preprocessing import clean_zeros

st.set_page_config(
    page_title="Heart Disease Prediction",
    page_icon="❤️",
    layout="centered"
)

st.title("❤️ Heart Disease Prediction")

st.write(
    "This application uses a machine learning model "
    "to predict heart disease status based on patient information."
)

st.warning(
    "This is an educational student project, not a medical "
    "diagnostic tool. Do not use its predictions for medical decisions."
)

model = joblib.load("heart_disease_model.joblib")

st.subheader("Patient Information")

age = st.number_input("Age", min_value=1, max_value=120, value=50)

sex = st.selectbox("Sex", ["M", "F"])

chest_pain = st.selectbox(
    "Chest Pain Type",
    ["ATA", "NAP", "ASY", "TA"]
)

resting_bp = st.number_input(
    "Resting Blood Pressure (mm Hg)",
    min_value=0,
    max_value=250,
    value=120
)

cholesterol = st.number_input(
    "Cholesterol (mg/dL)",
    min_value=0,
    max_value=700,
    value=200
)

fasting_bs = st.selectbox(
    "Fasting Blood Sugar > 120 mg/dL",
    [0, 1]
)

resting_ecg = st.selectbox(
    "Resting ECG",
    ["Normal", "ST", "LVH"]
)

max_hr = st.number_input(
    "Maximum Heart Rate",
    min_value=40,
    max_value=250,
    value=150
)

exercise_angina = st.selectbox(
    "Exercise-Induced Angina",
    ["N", "Y"]
)

oldpeak = st.number_input(
    "Oldpeak (ST Depression)",
    min_value=-5.0,
    max_value=10.0,
    value=1.0,
    step=0.1
)

st_slope = st.selectbox(
    "ST Slope",
    ["Up", "Flat", "Down"]
)

if st.button("Predict Heart Disease Status"):
    patient_data = pd.DataFrame([{
        "Age": age,
        "Sex": sex,
        "ChestPainType": chest_pain,
        "RestingBP": resting_bp,
        "Cholesterol": cholesterol,
        "FastingBS": fasting_bs,
        "RestingECG": resting_ecg,
        "MaxHR": max_hr,
        "ExerciseAngina": exercise_angina,
        "Oldpeak": oldpeak,
        "ST_Slope": st_slope
    }])

    prediction = model.predict(patient_data)[0]

    if prediction == 1:
        st.error("Model Prediction: Heart Disease (Class 1)")
    else:
        st.success("Model Prediction: No Heart Disease (Class 0)")

    st.caption(
        "This prediction is generated by a student machine-learning "
        "model and is not a medical diagnosis."
    )